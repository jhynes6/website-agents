def _require_env(name: str) -> str:
    val = (os.getenv(name) or "").strip()
    if not val:
        raise RuntimeError(f"Missing required env var: {name}")
    return val


def _normalize_index_host_for_sdk(raw: str) -> str:
    """
    Pinecone SDK expects the host string like:
      "client-knowledge-bases-xxxx.svc....pinecone.io"
    NOT a full URL with scheme.
    """
    h = (raw or "").strip()
    if h.startswith("https://"):
        h = h[len("https://") :]
    elif h.startswith("http://"):
        h = h[len("http://") :]
    return h.strip().strip("/")


